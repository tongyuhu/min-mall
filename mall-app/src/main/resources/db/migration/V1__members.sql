CREATE TABLE member (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, username VARCHAR(32) NOT NULL, password_hash VARCHAR(100) NOT NULL,
 nickname VARCHAR(64) NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE, auth_version BIGINT NOT NULL DEFAULT 0,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT uk_member_username UNIQUE(username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE member_address (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, member_id BIGINT NOT NULL, receiver VARCHAR(64) NOT NULL, phone VARCHAR(32) NOT NULL,
 province VARCHAR(64) NOT NULL, city VARCHAR(64) NOT NULL, district VARCHAR(64) NOT NULL, detail VARCHAR(255) NOT NULL,
 default_address BOOLEAN NOT NULL DEFAULT FALSE, created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_address_member FOREIGN KEY(member_id) REFERENCES member(id), INDEX idx_address_member(member_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
